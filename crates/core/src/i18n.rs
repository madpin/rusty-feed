pub fn is_supported_locale(locale: &str) -> bool {
    SUPPORTED_LOCALES.iter().any(|(code, _)| *code == locale)
}

pub fn is_supported_timezone(timezone: &str) -> bool {
    timezone == "UTC" || timezones::get_by_name(timezone).is_some()
}

pub fn text_direction(locale: &str) -> &'static str {
    if locale.split('-').next() == Some("ar") {
        "rtl"
    } else {
        "ltr"
    }
}

