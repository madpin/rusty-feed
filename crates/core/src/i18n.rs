pub fn format_date(value: OffsetDateTime, timezone: &str, format: &str) -> String {
    let value = timezones::get_by_name(timezone)
        .map(|timezone| value.to_timezone(timezone))
        .unwrap_or(value);
    let description: &[FormatItem<'_>] = match format {
        "dmy" => format_description!("[day padding:zero]/[month padding:zero]/[year]"),
        "ymd" => format_description!("[year]-[month padding:zero]-[day padding:zero]"),
        _ => format_description!("[month padding:zero]/[day padding:zero]/[year]"),
    };
    value
        .format(description)
        .unwrap_or_else(|_| value.date().to_string())
}

pub fn format_number(value: i64, format: &str) -> String {
    let separator = if format == "comma" { ',' } else { '.' };
    let raw = value.abs().to_string();
    let mut output = String::new();
    for (index, character) in raw.chars().rev().enumerate() {
        if index > 0 && index % 3 == 0 {
            output.push(separator);
        }
        output.push(character);
    }
    let mut output: String = output.chars().rev().collect();
    if value < 0 {
        output.insert(0, '-');
    }
    output
}

